package config

import (
	"os"
	"path/filepath"
	"testing"
)

func TestWindowsPowerShellUTF8Config(t *testing.T) {
	p := filepath.Join(t.TempDir(), "vrsync.env")
	if err := os.WriteFile(p, []byte("\ufeff# generated by Windows PowerShell\r\nDATABASE=pdv\r\n"), 0600); err != nil {
		t.Fatal(err)
	}
	v, _, err := loadFile(p)
	if err != nil || v["DATABASE"] != "pdv" {
		t.Fatalf("PowerShell UTF-8 file: %v %v", v, err)
	}
}
